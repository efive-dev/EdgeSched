inline std::string cocoClassName(int classId) {
  if (classId >= 0 && static_cast<size_t>(classId) < kCocoClassNames.size()) {
    return kCocoClassNames[static_cast<size_t>(classId)];
  }
  return "cls_" + std::to_string(classId);
}
